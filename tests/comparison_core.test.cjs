const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
vm.runInThisContext(fs.readFileSync('static/comparison_core.js', 'utf8'));
const C = global.QKBComparisonCore;
const source = new Uint8ClampedArray([150, 100, 50, 255]);
assert.deepEqual([...C.adjust(source, C.defaults())], [...source]);
assert.deepEqual([...C.adjust(source, {brightness: .1, contrast: 1.1})], [178, 123, 68, 255]);
assert.deepEqual([...source], [150, 100, 50, 255]);
const normalized = C.suggest({mean: 80, deviation: 10}, {mean: 120, deviation: 10});
assert.equal(normalized.contrast, 1);
assert.ok(Math.abs(normalized.brightness - 40 / 255) < .01);
assert.equal(C.suggest({mean: 80, deviation: 0}, {mean: 120, deviation: 20}).contrast, 1);
const stats = C.stats(source, 1, 1, [0, 0, 1, 1]);
assert.ok(Math.abs(stats.mean - 107.02) < .001);
assert.throws(() => C.stats(source, 1, 1, [0, 0, .01, .01]));
const method = {id:'mmasi',regions: [{id:'f',weight:.3},{id:'r',weight:.3},{id:'l',weight:.3},{id:'c',weight:.1}], fields:[{id:'area',options:Array(7)},{id:'darkness',options:Array(5)}]};
const inputs = Object.fromEntries(method.regions.map(r => [r.id,{area:6,darkness:4}]));
assert.equal(C.score(method, inputs), 24);
inputs.f.area = null;
assert.equal(C.score(method, inputs), null);
inputs.f.area = 7;
assert.equal(C.score(method, inputs), null);
assert.deepEqual(C.fitSize(1000, 2000, 600, 400), {width: 200, height: 400});
assert.deepEqual(C.fitSize(2000, 1000, 600, 400), {width: 600, height: 300});
assert.deepEqual(C.fitSize(1000, 2000, 600, 400, 2), {width: 400, height: 800});
assert.deepEqual(C.projectPatch([.25, .25, .5, .5], [.5, .5, .5, .5]), [0, 0, .5, .5]);
assert.equal(C.projectPatch([0, 0, .1, .1], [.5, .5, .5, .5]), null);
const evenPixels = new Uint8ClampedArray(100 * 100 * 4).fill(128);
for (let i = 3; i < evenPixels.length; i += 4) evenPixels[i] = 255;
const candidates = C.patchCandidates(evenPixels, 100, 100);
assert.equal(candidates.length, 3);
for (const [x, y, w, h] of candidates) assert.ok(x >= 0 && y >= 0 && x + w <= 1 && y + h <= 1);
assert.equal(C.patchCandidates(new Uint8ClampedArray(100 * 100 * 4).fill(255), 100, 100).length, 0);
assert.equal(C.patchCandidates(new Uint8ClampedArray(100 * 100 * 4), 100, 100).length, 0);
console.log('Comparison pixels, grading, fit geometry, overlays, and patch suggestions passed.');
